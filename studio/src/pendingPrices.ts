/** Решение Макса 16.10.2026: позиции кухни без счёта поставщика — не «нет цены», а «цена будет после финального расчёта конструктором».
 *  Итог проекта = сумма известных позиций; рядом — явная строка «Позиции после финального расчёта конструктором: N».
 *  Поставщик и ориентир клиенту — только менеджеру (источник строки сметы). Ориентир в итог не входит и клиенту не показывается:
 *  в публичной сборке строки с названием поставщика заменяются пустыми (scripts/public-build.ts, SENSITIVE_NAMES), поэтому каждая
 *  подпись ниже — одной строкой вместе с поставщиком. Цена, введённая в смете вручную, снимает пометку (строка становится обычной). */
export type PendingPrice = { source: string };
const RULES: [RegExp, string][] = [
  [/^kitchen-leg$/, 'ФАМ: опора кухонная H100-120 — цена после финального расчёта конструктором'],
  [/^kitchen-clip$/, 'ФАМ: клипса цоколя — цена после финального расчёта конструктором'],
  // ящик Axis PRO в смете — комплект фурнитуры на один ящик: ориентир — за комплект (= за ящик)
  [/^axis-pro:/, 'Мегатрейд: ящик Axis PRO, комплект на ящик — цена после финального расчёта конструктором; ориентир клиенту ~7 000 ₽ за комплект'],
  [/^axis-rail:/, 'Мегатрейд: релинг Axis PRO — цена после финального расчёта конструктором'],
  [/^kitchen-hanger$/, 'ФАС: навес мебельный — цена после финального расчёта конструктором; ориентир клиенту ~120 ₽ за шт'],
  [/^kitchen-hanger-cap$/, 'ФАС: заглушка навеса — цена после финального расчёта конструктором'],
  [/^worktop:/, 'Премиал (предварительно): столешница — цена после финального расчёта конструктором'],
];
/** Позиция без цены, которую конструктор считает в финальном расчёте (а не «нет цены»). */
export function pendingPrice(id: string): PendingPrice | null {
  const r = RULES.find(([re]) => re.test(id));
  return r ? { source: r[1] } : null;
}
