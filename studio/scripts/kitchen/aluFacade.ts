// Фасад в алюминиевом профиле из Базиса (статистика по 34 кухням, 09.10.2026): 16 модулей — навесные k17, k20, k21, k27,
// пеналы k08, k20, k30, k31, прочие k27, k28. В проекте Базиса от такого фасада есть только наполнение (стекло или зеркало 4 мм,
// панель «Наполнение» из набора «Фасад в узком/широком алюминиевом профиле») и профиль рамки без сетки (категория «профиль»,
// координаты вне модуля). Габарит рамки и петли в проекте не заданы (у 12 из 16 петель нет вовсе), поэтому студия рамку
// не выдумывает: модуль честно остаётся сырым (в импорте — геометрия Базиса). Зеркало (k21 m05–m07) сверщик панелью не считает,
// поэтому без этой причины модуль без фасада мог бы пройти сверку молча.
import type { RefModule, RefPanel } from "./compare";

const ALU = /алюминиев\S*\s+профил/i;

/** Наполнение алюминиевого фасада Базиса: стекло/зеркало в плоскости фасадов из набора «… в алюминиевом профиле». */
export function isAluFilling(p: RefPanel): boolean {
  return p.axis === "z" && (p.kind === "glass" || p.kind === "mirror") && ALU.test(p.grp ?? "");
}

/** Причина «не поддержано» для модуля с фасадом в алюминиевом профиле или null. */
export function aluFacadeReason(ref: RefModule): string | null {
  const n = ref.panels.filter(isAluFilling).length;
  return n ? `фасад в алюминиевом профиле Базиса (наполнение ${n} шт., рамка — профиль без сетки, габарит рамки в проекте не задан) — пока не поддержано` : null;
}
