// Угловые навесные Базиса (wall-corner, 8 модулей в 34 кухнях, разбор 09.10.2026). Параметрика студии — прямоугольный корпус;
// что в него не укладывается, честно остаётся «сырым» (импорт кладёт детали Базиса как есть, raw.counts — фурнитура):
//  — диагональный угловой (k02 m06, k03 m10, k09 m08): план пятиугольник — боковины разной глубины (≈580 и ≈335), фальш по фронту
//    и дверь под 45°; «Скос фронта» студии даёт только трапецию без фальши, диагонального корпуса нет;
//  — прямой угловой с глухой частью из фасада («Фронтальная» фасадного материала рядом с дверью, k01 m06, k25 m18) — глухой
//    фальш-фасад в ряду дверей студия не строит; неравные створки (k02 m02: 338 и 359) — студия делит проём поровну.
import type { RefModule } from "./compare";

const r0 = (v: number) => Math.round(v);

/** Причина, по которой угловой навесной остаётся сырым, или null, если он прямоугольный. */
export function wallCornerRaw(ref: RefModule): string | null {
  const diag = ref.panels.find((p) => p.axis === "z" && p.box[3] - p.box[0] > 60 && p.box[5] - p.box[2] > 60 && p.box[4] - p.box[1] > 200);
  if (diag) return `угловой навесной с диагональным фасадом (дверь под 45°, ${r0(diag.box[3] - diag.box[0])}×${r0(diag.box[5] - diag.box[2])} в плане) — в студии нет диагонального корпуса, модуль остаётся сырым`;
  return null;
}
